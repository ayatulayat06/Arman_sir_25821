# Demonstrating Comparison Operators

x= int(input("Enter first number: "))
y= int(input("Enter second number: "))

print("x is equal to (x==y):", x==y)
print("x is not equal to (x!=y):", x!=y)
print("x is greater than (x>y):", x>y)
print("x is less than (x<y):", x<y)
print("x is greater than or equal to (x>=y):", x>=y)
print("x is less than or equal to (x<=y):", x<=y)
